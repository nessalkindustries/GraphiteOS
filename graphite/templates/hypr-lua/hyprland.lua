local home = os.getenv("HOME")
-- optional file: a missing or broken file must not kill the whole config. dofile, not require:
-- require treats "." as a directory separator, which breaks paths under ~/.config.
local function optional(path)
    local f = io.open(path .. ".lua", "r")
    if not f then return end
    f:close()
    local ok, err = pcall(dofile, path .. ".lua")
    if not ok then print("graphite: " .. path .. ".lua failed: " .. tostring(err)) end
end

