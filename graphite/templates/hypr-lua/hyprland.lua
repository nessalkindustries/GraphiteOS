-- Autostart (exec-once): graphite-hypr-autostart runs once per Hyprland instance, so calling it
-- from several places is safe. The start event alone did not start anything on 0.57.1.
local function autostart() hl.exec_cmd("graphite-hypr-autostart") end
hl.on("hyprland.start", autostart)
